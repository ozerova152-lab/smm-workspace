test('резервная копия переносит проекты, карточки и замеры и защищает текущие данные', async ({ page, browser }, info) => {
  test.setTimeout(60_000)
  const { readFile } = await import('node:fs/promises')
  const original = {
    format: 'smm-workspace', version: 1,
    projects: [{
      id: 'sample-project', name: 'Проект из копии', description: '',
      platforms: [{ id: 'sample-platform', projectId: 'sample-project', name: 'Telegram', formats: ['Пост'], metrics: ['Просмотры'], checklist: [] }],
    }],
    cards: [{
      id: 'sample-post', projectId: 'sample-project', platformId: 'sample-platform', kind: 'Публикация', title: 'Пост из копии',
      body: '', status: 'Опубликовано', format: 'Пост', audience: '', dueDate: '', plannedDate: '2026-11-20',
      publishedDate: '2026-11-20', link: '', nextStep: '', archived: false,
    }],
    analytics: {
      measurements: [{ platformId: 'sample-platform', publicationId: 'sample-post', metric: 'Просмотры', value: 42, from: '2026-11-21', to: '', source: 'Пример' }],
      references: [], notes: [],
    },
  }
  const copy = { name: 'copy.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) }
  const select = (target: typeof page) => target.locator('input[type=file]')
  await page.goto(testUrl + '?mode=demo')
  await expect(page.getByRole('heading', { name: 'Городской сад' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Резервная копия' })).toHaveCount(0)

  await page.goto(testUrl + '?state=backup-loading')
  await page.getByRole('button', { name: 'Резервная копия' }).click()
  await expect(page.getByText('Выберите файл резервной копии')).toBeVisible()
  await page.screenshot({ path: info.outputPath('backup-empty.png') })
  await select(page).setInputFiles({ ...copy, buffer: Buffer.from('{"format":"unknown"}') })
  await expect(page.getByText('Проверяем копию…')).toBeVisible()
  await page.screenshot({ path: info.outputPath('backup-loading.png') })
  await expect(page.getByRole('alert')).toContainText('Файл не подходит')
  await page.screenshot({ path: info.outputPath('backup-invalid.png') })
  await select(page).setInputFiles(copy)
  await page.getByRole('button', { name: 'Восстановить данные' }).click()
  await expect(page.getByText('Данные восстановлены')).toBeVisible()

  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать копию' }).click()
  const exported = await (await download).path()
  expect(JSON.parse(await readFile(exported, 'utf8'))).toEqual(original)

  const another = await browser.newPage()
  try {
    await another.clock.setFixedTime(new Date('2026-11-24T12:00:00'))
    await another.goto(testUrl + '?state=backup-error')
    await another.getByRole('button', { name: 'Создать проект' }).click()
    await another.getByLabel('Название', { exact: true }).fill('До восстановления')
    await another.getByRole('button', { name: 'Сохранить проект' }).click()
    await another.getByRole('heading', { name: 'До восстановления' }).waitFor()
    await another.getByRole('button', { name: 'К проектам' }).click()
    await another.getByRole('button', { name: 'Резервная копия' }).click()

    await select(another).setInputFiles(exported)
    const restore = another.getByRole('button', { name: 'Восстановить данные' })
    await expect(restore).toBeDisabled()
    await another.screenshot({ path: info.outputPath('backup-preview.png') })
    await another.getByRole('button', { name: 'Отмена' }).click()
    await expect(restore).toHaveCount(0)
    await select(another).setInputFiles(exported)
    await another.getByRole('checkbox', { name: 'Подтверждаю замену текущих данных' }).check()
    await restore.click()
    await expect(another.getByRole('alert').filter({ hasText: 'Не удалось восстановить данные' })).toContainText('Текущие данные сохранены')
    const current = another.waitForEvent('download')
    await another.getByRole('button', { name: 'Скачать копию' }).click()
    const previous = JSON.parse(await readFile(await (await current).path(), 'utf8'))
    expect(previous.projects[0].name).toBe('До восстановления')
    await restore.click()
    await expect(another.getByText('Данные восстановлены')).toBeVisible()
    await another.getByRole('button', { name: 'Открыть проекты' }).click()
    await expect(another.getByRole('heading', { name: 'Проект из копии' })).toBeVisible()
    await expect(another.getByRole('heading', { name: 'До восстановления' })).toHaveCount(0)
    await another.getByRole('button', { name: 'Открыть проект' }).click()
    await expect(another.getByRole('button', { name: 'Пост из копии' })).toBeVisible()
    await another.getByRole('button', { name: 'Перейти к аналитике' }).click()
    await expect(another.getByRole('table', { name: 'Замеры' }).getByRole('row').filter({ hasText: 'Пост из копии' })).toContainText('42')
  } finally { await another.close() }
})
