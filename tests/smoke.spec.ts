  await expect(star).toHaveCSS('animation-name', 'twinkle')
  await page.getByRole('button', { name: 'Пауза анимации' }).click()
  await expect(star).toHaveCSS('animation-play-state', 'paused')
  await page.getByRole('button', { name: 'Включить анимацию' }).click()
  await expect(star).toHaveCSS('animation-play-state', 'running')
